/*
  Writes THIRD-PARTY-NOTICES.txt: every library that ships inside AERONEX,
  with its licence and copyright notice, as MIT, BSD, ISC and Apache require.

  "Ships" means the app's production dependencies (bundled into the web build)
  and the Windows shell's updater (bundled into desktop/main.bundle.cjs),
  with everything they depend on.

  usage: node scripts/third-party-notices.mjs          write the file
         node scripts/third-party-notices.mjs --check  fail if it is out of date
*/
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(ROOT, "THIRD-PARTY-NOTICES.txt");
const root = JSON.parse(readFileSync(join(ROOT, "package.json"), "utf8"));
const SHELL = ["electron-updater"];

/** Where Node would find `name` when required from `fromDir`. */
function resolve(name, fromDir) {
  let dir = fromDir;
  for (;;) {
    const p = join(dir, "node_modules", name);
    if (existsSync(join(p, "package.json"))) return p;
    if (dir === ROOT || dir === dirname(dir)) return null;
    dir = dirname(dir);
  }
}

const seen = new Map();
function walk(name, fromDir) {
  const dir = resolve(name, fromDir);
  if (!dir || seen.has(dir)) return;
  const pkg = JSON.parse(readFileSync(join(dir, "package.json"), "utf8"));
  seen.set(dir, pkg);
  for (const dep of Object.keys(pkg.dependencies ?? {})) walk(dep, dir);
}
for (const dep of [...Object.keys(root.dependencies ?? {}), ...SHELL]) walk(dep, ROOT);

const licenceOf = (pkg) =>
  typeof pkg.license === "string" ? pkg.license : pkg.license?.type ?? (Array.isArray(pkg.licenses) ? pkg.licenses.map((l) => l.type ?? l).join(" OR ") : "UNKNOWN");

function licenceText(dir) {
  const file = readdirSync(dir).find((f) => /^(licen[cs]e|copying)(\.(md|txt|markdown))?$/i.test(f));
  return file ? readFileSync(join(dir, file), "utf8").replace(/\r\n/g, "\n").trim() : null;
}

/** For a package whose package.json names no licence, the licence its LICENSE file states. */
function fromText(text) {
  const head = (text ?? "").slice(0, 200);
  if (/^MIT License/i.test(head)) return "MIT";
  if (/^ISC License/i.test(head)) return "ISC";
  if (/Apache License\s+Version 2\.0/i.test(head)) return "Apache-2.0";
  return "UNKNOWN";
}

const entries = [...seen.entries()]
  .map(([dir, pkg]) => {
    const text = licenceText(dir);
    const declared = licenceOf(pkg);
    const repo = typeof pkg.repository === "string" ? pkg.repository : pkg.repository?.url;
    return { name: pkg.name, version: pkg.version, licence: declared === "UNKNOWN" ? fromText(text) : declared, text, home: pkg.homepage ?? repo ?? "" };
  })
  .sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));

const bar = "-".repeat(78);
const out = [
  "Third-party software in AERONEX Ground Station",
  "",
  "AERONEX is licensed under the Apache License 2.0 (see LICENSE and NOTICE).",
  "It includes the following libraries, each under its own licence.",
  "Generated by scripts/third-party-notices.mjs; do not edit by hand.",
  "",
  ...entries.map((e) => `  ${e.name} ${e.version}  (${e.licence})`),
  "",
  ...entries.flatMap((e) => [bar, `${e.name} ${e.version}`, `Licence: ${e.licence}`, ...(e.home ? [`Source: ${e.home.replace(/^git\+/, "")}`] : []), "", e.text ?? `No licence file is included in the package; its package.json declares ${e.licence}.`, ""]),
].join("\n");

const unknown = entries.filter((e) => e.licence === "UNKNOWN");
if (unknown.length) {
  console.error(`No licence declared by: ${unknown.map((e) => e.name).join(", ")}`);
  process.exit(1);
}

if (process.argv.includes("--check")) {
  const current = existsSync(OUT) ? readFileSync(OUT, "utf8") : "";
  if (current !== out) {
    console.error("THIRD-PARTY-NOTICES.txt is out of date: run node scripts/third-party-notices.mjs");
    process.exit(1);
  }
  console.log(`THIRD-PARTY-NOTICES.txt is up to date (${entries.length} packages).`);
} else {
  writeFileSync(OUT, out);
  console.log(`Wrote THIRD-PARTY-NOTICES.txt: ${entries.length} packages.`);
}
