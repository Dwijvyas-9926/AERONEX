#!/usr/bin/env node
/*
  Builds src/firmware/boards.generated.ts from an ArduPilot source tree: for
  every flight-controller board ArduPilot supports, its APJ board id (what
  the bootloader reports) and the USB vendor ids its firmware and bootloader
  use. Run it again when ArduPilot adds boards:

      node scripts/gen-boards.mjs ~/ardupilot

  Board ids come from APJ_BOARD_ID in each board's hwdef.dat (following
  "include" lines), resolved through Tools/AP_Bootloader/board_types.txt.
  Peripheral (AP_Periph) and IO-coprocessor boards are left out: they do not
  run ArduCopter.
*/
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const root = process.argv[2];
if (!root) {
  console.error("usage: node scripts/gen-boards.mjs <ardupilot source tree>");
  process.exit(1);
}
const hwdefDir = path.join(root, "libraries/AP_HAL_ChibiOS/hwdef");
const types = new Map();
for (const line of readFileSync(path.join(root, "Tools/AP_Bootloader/board_types.txt"), "utf8").split("\n")) {
  const m = /^\s*(\S+)\s+(\d+)/.exec(line);
  if (m) types.set(m[1], Number(m[2]));
}

/** A hwdef file with its includes expanded (only the lines we read). */
function expand(file, seen = new Set()) {
  if (seen.has(file) || !existsSync(file)) return [];
  seen.add(file);
  const out = [];
  for (const raw of readFileSync(file, "utf8").split("\n")) {
    const line = raw.replace(/#.*$/, "").trim();
    const inc = /^include\s+(\S+)/.exec(line);
    if (inc) out.push(...expand(path.resolve(path.dirname(file), inc[1]), seen));
    else if (line) out.push(line);
  }
  return out;
}

const last = (lines, key) => {
  let v;
  for (const l of lines) {
    const m = new RegExp(`^${key}\\s+(.+)$`).exec(l);
    if (m) v = m[1].trim();
  }
  return v;
};

const boards = [];
// 0x1209 ArduPilot's default; 0x26ac 3D Robotics (the PX4 bootloader many older Pixhawks still have); 0x0483 STMicroelectronics.
const vids = new Set([0x1209, 0x26ac, 0x0483]);
for (const name of readdirSync(hwdefDir).sort()) {
  const app = path.join(hwdefDir, name, "hwdef.dat");
  if (!existsSync(app)) continue;
  const lines = expand(app);
  const text = lines.join("\n");
  if (/AP_PERIPH|IOMCU_FW|^name\s/m.test(text) || /iomcu/i.test(name)) continue;
  const idRaw = last(lines, "APJ_BOARD_ID");
  if (!idRaw) continue;
  const id = /^\d+$/.test(idRaw) ? Number(idRaw) : types.get(idRaw);
  if (id === undefined) {
    console.warn(`skip ${name}: unknown board id ${idRaw}`);
    continue;
  }
  const mcu = last(lines, "MCU")?.split(/\s+/)[1] ?? "";
  const flashKb = Number(last(lines, "FLASH_SIZE_KB") ?? 0);
  // USB ids as chibios_hwdef.py sets them: 1209:5740 for firmware, 1209:5741 for the bootloader, unless the board says.
  const usb = (f, pid) => {
    const l = expand(f);
    const v = Number(last(l, "USB_VENDOR") ?? 0x1209);
    const p = Number(last(l, "USB_PRODUCT") ?? pid);
    vids.add(v);
    return [v, p];
  };
  const blFile = path.join(hwdefDir, name, "hwdef-bl.dat");
  boards.push({ name, id, mcu, flashKb, app: usb(app, 0x5740), bl: existsSync(blFile) ? usb(blFile, 0x5741) : null });
}

const hex = (pair) => pair.map((v) => `0x${v.toString(16).padStart(4, "0")}`).join(", ");
const byId = new Map();
for (const b of boards) {
  if (!byId.has(b.id)) byId.set(b.id, []);
  byId.get(b.id).push(b);
}

const out = `/*
  Generated by scripts/gen-boards.mjs from ArduPilot's hardware definitions
  (${boards.length} flight-controller boards). Do not edit by hand.

  BOARDS: APJ board id (what the bootloader reports) → the ArduPilot
  platforms (firmware build names) built for it, with the MCU and its flash.
  USB_VENDORS: every USB vendor id their firmware or bootloader uses.
*/
export interface BoardBuild {
  platform: string;
  mcu: string;
  flashKb: number;
  /** USB vendor and product id of its firmware, and of its bootloader (null when ArduPilot does not build one for it). */
  app: [number, number];
  bl: [number, number] | null;
}

export const BOARDS: Record<number, BoardBuild[]> = {
${[...byId.keys()]
  .sort((a, b) => a - b)
  .map((id) => `  ${id}: [${byId.get(id).map((b) => `{ platform: ${JSON.stringify(b.name)}, mcu: ${JSON.stringify(b.mcu)}, flashKb: ${b.flashKb}, app: [${hex(b.app)}], bl: ${b.bl ? `[${hex(b.bl)}]` : "null"} }`).join(", ")}],`)
  .join("\n")}
};

export const USB_VENDORS: number[] = [${[...vids].sort((a, b) => a - b).map((v) => `0x${v.toString(16).padStart(4, "0")}`).join(", ")}];
`;
const dest = path.join(path.dirname(new URL(import.meta.url).pathname), "../src/firmware/boards.generated.ts");
writeFileSync(dest, out);
console.log(`${boards.length} boards, ${byId.size} board ids, ${vids.size} USB vendors → ${dest}`);
